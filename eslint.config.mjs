import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next. The `**/` prefix matters here: a
    // Next build run inside `src/` leaves a stale `src/.next`, and linting its
    // bundled output added 1,334 bogus errors to every `npm run lint`.
    "**/.next/**",
    "**/out/**",
    "**/build/**",
    "next-env.d.ts",
    "**/next-env.d.ts",
    // Build and deploy output, plus the vendored pdf.js worker. Linting these
    // accounted for every "20,000 problems" a plain `npm run lint` reported.
    ".open-next/**",
    "freebuff-sites-build/**",
    ".wrangler/**",
    ".build/**",
    "public/pdf.worker.min.mjs",
    // Generated by Freebuff Sites on every publish; its form is not ours to
    // lint and a diff here would be overwritten.
    "freebuff.open-next.config.ts",
  ]),
]);

export default eslintConfig;
